SET client_encoding = 'UTF8';

-- Append-only history used by the stage-10 settings interface.
CREATE TABLE IF NOT EXISTS public.device_settings_audit
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    string_id VARCHAR(128) NOT NULL,
    device_code VARCHAR(64) NOT NULL,
    type SMALLINT NOT NULL CHECK (type BETWEEN 1 AND 4),
    old_value TEXT,
    new_value TEXT NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by INTEGER NOT NULL REFERENCES public.users(id)
);

CREATE INDEX IF NOT EXISTS idx_device_settings_audit_device
    ON public.device_settings_audit (device_code, id);

CREATE INDEX IF NOT EXISTS idx_device_settings_audit_user
    ON public.device_settings_audit (changed_by, changed_at);

COMMENT ON TABLE public.device_settings_audit IS
    'Immutable history of device connection setting changes';
COMMENT ON COLUMN public.device_settings_audit.old_value IS
    'Value before the administrator update; null for the first persisted value';
COMMENT ON COLUMN public.device_settings_audit.new_value IS
    'Validated value stored by the administrator update';
