# Интеграция RGS.Front в RGSCenter

## Краткое решение

Использовать `RGS.Front` как визуальный прототип, а рабочий frontend хранить в `RGSCenter` и включать в единый Spring Boot JAR. Next.js и отдельный frontend-сервер не нужны: текущему многостраничному приложению лучше подходят Thymeleaf и обычный JavaScript с API того же origin.

Авторизация выполняется в два этапа:

1. Вход пользователя по логину и паролю.
2. Получение монопольного доступа по мастер-паролю.

Из `RGS.Front` переносится дизайн, разметка и SVG-логотип. Текущий демонстрационный `script.js` с переключением по чётности минуты не переносится.

## Изменения

- Оформить существующий `/login` в стиле макета RGS.Front, сохранив поля `login`, `password`, CSRF и `POST /auth/login`.
- Добавить защищённую страницу `GET /access?returnTo=...` с состояниями:
  - `LOADING`;
  - `BUSY` с IP занятого клиента;
  - `ENTER_PASS`;
  - переход на запрошенную страницу после получения токена.
- После успешного `/auth/login` перенаправлять на `/access`, а не сразу на `/`.
- Сохранять только one-client-токен в `sessionStorage` под ключом `rgs.onlyOne.lockToken`. Обычный `RGS_AUTH_TOKEN` продолжает храниться в защищённой HttpOnly cookie.
- Реализовать frontend как явный автомат состояний:
  - токен существует > `GET /api/onlyOne/checkMe`;
  - токена нет или он недействителен > `GET /api/onlyOne/checkBusy`;
  - система свободна > форма мастер-пароля;
  - система занята > экран `BUSY`, повторная проверка каждые 5 секунд;
  - правильный пароль > `POST /api/onlyOne/enter`, сохранение токена и переход на `returnTo`;
  - активная рабочая страница > `POST /api/onlyOne/updateBusy` каждые 60 секунд.
- Во все рабочие страницы добавить общий guard:
  - до завершения `checkMe` показывать полноэкранный `LOADING`;
  - при валидном токене открывать содержимое;
  - при отсутствии или истечении токена переходить на `/access?returnTo=<current-path>`.
- Общий клиент запросов должен добавлять к изменяющим запросам:
  - CSRF-заголовок;
  - `X-Lock-Token`;
  - обработку `401` и `423`.
- При logout сначала выполнить best-effort `POST /api/onlyOne/exit`, удалить токен из `sessionStorage`, затем отправить существующий `POST /auth/logout`.
- Событие закрытия вкладки не считать надёжным способом освобождения блокировки; окончательной защитой остаётся TTL.
- Интерфейс обоих этапов сделать единообразным и русскоязычным. Удалить неработающую кнопку `Forgot password?`.

## Маршруты и безопасность

- Новый интерфейс: `GET /access?returnTo=/measurement-emulator`.
- Существующие `/api/onlyOne/*` и их JSON-контракты не изменять.
- `returnTo` разрешать только как локальный абсолютный путь, начинающийся с одного `/`. Запрещать `//`, схемы и внешние адреса; значение по умолчанию — `/`.
- Для неавторизованного HTML-запроса сохранять исходный локальный путь через `/login?returnTo=...`.
- `/access` должен требовать обычную пользовательскую авторизацию.
- CSS, JavaScript, логотип и favicon обслуживать Spring Boot из `/static`; добавить публичный доступ к `/images/**`.
- CORS и отдельный reverse proxy не требуются, поскольку UI и API работают на одном origin.
- Незавершённую untracked-папку `C:\Projects\RGSCenter\frontend` не использовать и не изменять.

## Проверка

- Неавторизованный пользователь сначала попадает на `/login`.
- После корректного входа открывается `/access`, а после получения аренды — исходная страница.
- Существующий валидный токен пропускает пользователя без повторного ввода мастер-пароля.
- Невалидный или истёкший токен удаляется и возвращает пользователя к проверке занятости.
- Второй браузер видит `BUSY`, IP владельца и автоматически получает форму после освобождения или истечения TTL.
- Неверный мастер-пароль не создаёт токен и позволяет повторить ввод.
- Heartbeat продлевает аренду; ответ `401/423` закрывает рабочий экран и возвращает на `/access`.
- Все POST-команды приложения содержат CSRF и `X-Lock-Token`.
- Logout освобождает аренду и отзывает пользовательский cookie-токен.
- Добавить MockMvc-тесты маршрутов, безопасного `returnTo` и редиректов; проверить JavaScript через `node --check` и пройти два браузерных сценария с разными `sessionStorage`.

## Принятые условия

- `RGSCenter` является единственным production-источником frontend-кода.
- `RGS.Front` остаётся отдельным репозиторием прототипов и не подключается как submodule.
- Обычная многопользовательская авторизация и предупреждение о нескольких подключённых браузерах сохраняются.
- Монопольная аренда ограничивает управление оборудованием, но не заменяет пользовательскую аутентификацию.
