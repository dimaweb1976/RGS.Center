CREATE TABLE IF NOT EXISTS appusers
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT,
    treename VARCHAR(64) NOT NULL,
    materialized_pathname VARCHAR(256),
    login VARCHAR(256) NOT NULL UNIQUE,
    chldrn INTEGER NOT NULL DEFAULT 0,
    scrthsh VARCHAR(256) NOT NULL,
    change_pass_next_login BOOLEAN NOT NULL DEFAULT FALSE,
    email VARCHAR(256),
    role BIGINT NOT NULL DEFAULT 2,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    registration_date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS auth_sessions
(
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES appusers(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    remote_address VARCHAR(64),
    user_agent VARCHAR(512)
);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_active
    ON auth_sessions (revoked_at, expires_at, last_seen_at);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_user
    ON auth_sessions (user_id);
