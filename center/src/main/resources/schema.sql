-- Spring Boot executes this idempotent schema on every application startup
-- because spring.sql.init.mode=always. It is valid for PostgreSQL and H2 tests.

-- Application roles. IDs 1..3 are stable because users.role references them.
CREATE TABLE IF NOT EXISTS roles
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    rolename VARCHAR(256) NOT NULL UNIQUE
);

MERGE INTO roles AS target
USING (VALUES (1, 'service'),
              (2, 'administrator'),
              (3, 'operator')) AS source(id, rolename)
ON target.id = source.id OR target.rolename = source.rolename
WHEN NOT MATCHED THEN
    INSERT (id, rolename) VALUES (source.id, source.rolename);

-- Passwords are stored only as BCrypt hashes. Authorization resolves the role
-- through users.role -> roles.id during login and token authentication.
CREATE TABLE IF NOT EXISTS users
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(256) NOT NULL UNIQUE,
    hash VARCHAR(256) NOT NULL,
    role INTEGER NOT NULL REFERENCES roles(id)
);

MERGE INTO users AS target
USING (VALUES
          ('service', '$2a$12$AqNK6H1evUFz9v9WwHEq4OOYFOuRSAmP7p9tCSUnpIDRoxgGLtKQK', 1),
          ('admin', '$2a$12$6A1iQNunjykuPeE5P3Sviepn2ZtKZThHkoghPKcro1MGwoMAniLm6', 2),
          ('operator', '$2a$12$6ThV7BMKVSq.Z/BAkjyYaO3x.LlIoi/VSYdZuJUez5YZ0BuoKKfDu', 3)
      ) AS source(login, hash, role)
ON target.login = source.login
WHEN NOT MATCHED THEN
    INSERT (login, hash, role) VALUES (source.login, source.hash, source.role);

-- Each browser token has one server-side session. token_hash contains SHA-256;
-- the raw bearer token exists only in the browser's HttpOnly cookie.
CREATE TABLE IF NOT EXISTS auth_sessions
(
    id UUID PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    remote_address VARCHAR(64),
    user_agent VARCHAR(512)
);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_active
    ON auth_sessions (revoked_at, expires_at, last_seen_at);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_user
    ON auth_sessions (user_id);

COMMENT ON TABLE roles IS 'Справочник ролей пользователей RGSCenter';
COMMENT ON TABLE users IS 'Пользователи RGSCenter';
COMMENT ON COLUMN users.hash IS 'BCrypt-хэш пароля; пароль в открытом виде не хранится';
COMMENT ON TABLE auth_sessions IS 'Серверные сессии токен-аутентификации RGSCenter';
