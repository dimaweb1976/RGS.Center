-- Spring Boot executes this idempotent schema on every application startup
-- because spring.sql.init.mode=always. It is valid for PostgreSQL and H2 tests.

-- Application roles. IDs 1..3 are stable because users.role references them.
CREATE TABLE IF NOT EXISTS roles
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    rolename VARCHAR(256) NOT NULL UNIQUE
);

MERGE INTO roles AS target
USING (VALUES (1, 'service'),
              (2, 'administrator'),
              (3, 'operator')) AS source(id, rolename)
ON target.id = source.id OR target.rolename = source.rolename
WHEN NOT MATCHED THEN
    INSERT (id, rolename) VALUES (source.id, source.rolename);

-- Passwords are stored only as BCrypt hashes. Authorization resolves the role
-- through users.role -> roles.id during login and token authentication.
CREATE TABLE IF NOT EXISTS users
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(256) NOT NULL UNIQUE,
    hash VARCHAR(256) NOT NULL,
    role INTEGER NOT NULL REFERENCES roles(id)
);

MERGE INTO users AS target
USING (VALUES
          ('service', '$2a$12$AqNK6H1evUFz9v9WwHEq4OOYFOuRSAmP7p9tCSUnpIDRoxgGLtKQK', 1),
          ('admin', '$2a$12$6A1iQNunjykuPeE5P3Sviepn2ZtKZThHkoghPKcro1MGwoMAniLm6', 2),
          ('operator', '$2a$12$6ThV7BMKVSq.Z/BAkjyYaO3x.LlIoi/VSYdZuJUez5YZ0BuoKKfDu', 3)
      ) AS source(login, hash, role)
ON target.login = source.login
WHEN NOT MATCHED THEN
    INSERT (login, hash, role) VALUES (source.login, source.hash, source.role);

-- Each browser token has one server-side session. token_hash contains SHA-256;
-- the raw bearer token exists only in the browser's HttpOnly cookie.
CREATE TABLE IF NOT EXISTS auth_sessions
(
    id UUID PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    remote_address VARCHAR(64),
    user_agent VARCHAR(512)
);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_active
    ON auth_sessions (revoked_at, expires_at, last_seen_at);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_user
    ON auth_sessions (user_id);

-- Device connection settings. Production defaults are deployed by dbscripts;
-- this portable definition also supports H2-backed application tests.
CREATE TABLE IF NOT EXISTS device_settings
(
    string_id VARCHAR(128) PRIMARY KEY,
    device_code VARCHAR(64) NOT NULL,
    type SMALLINT NOT NULL CHECK (type BETWEEN 1 AND 4),
    boolean_value BOOLEAN,
    long_value BIGINT,
    double_value DOUBLE PRECISION,
    string_value TEXT,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by INTEGER REFERENCES users(id),
    CONSTRAINT ck_device_settings_typed_value CHECK
    (
        (type = 1 AND boolean_value IS NOT NULL
                  AND long_value IS NULL
                  AND double_value IS NULL
                  AND string_value IS NULL)
        OR
        (type = 2 AND boolean_value IS NULL
                  AND long_value IS NOT NULL
                  AND double_value IS NULL
                  AND string_value IS NULL)
        OR
        (type = 3 AND boolean_value IS NULL
                  AND long_value IS NULL
                  AND double_value IS NOT NULL
                  AND string_value IS NULL)
        OR
        (type = 4 AND boolean_value IS NULL
                  AND long_value IS NULL
                  AND double_value IS NULL
                  AND string_value IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_device_settings_device
    ON device_settings (device_code, string_id);

CREATE INDEX IF NOT EXISTS idx_device_settings_updated_by
    ON device_settings (updated_by);

-- Append-only history of device connection setting changes.
CREATE TABLE IF NOT EXISTS device_settings_audit
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    string_id VARCHAR(128) NOT NULL,
    device_code VARCHAR(64) NOT NULL,
    type SMALLINT NOT NULL CHECK (type BETWEEN 1 AND 4),
    old_value TEXT,
    new_value TEXT NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by INTEGER NOT NULL REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_device_settings_audit_device
    ON device_settings_audit (device_code, id);

CREATE INDEX IF NOT EXISTS idx_device_settings_audit_user
    ON device_settings_audit (changed_by, changed_at);

-- Current operator defaults used by automatic and manual measurements.
CREATE TABLE IF NOT EXISTS measurement_parameters
(
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    measuring_time_minutes BIGINT NOT NULL CHECK (measuring_time_minutes BETWEEN 1 AND 1440),
    volume_ml DOUBLE PRECISION NOT NULL CHECK (volume_ml > 0 AND volume_ml <= 10000),
    geometry VARCHAR(32) NOT NULL,
    tare_mass_grams DOUBLE PRECISION NOT NULL CHECK (tare_mass_grams >= 0 AND tare_mass_grams <= 100000),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

MERGE INTO measurement_parameters AS target
USING (VALUES (1, 120, 300.0, 'BOTTLE', 0.0, 0))
    AS source(id, measuring_time_minutes, volume_ml, geometry, tare_mass_grams, version)
ON target.id = source.id
WHEN NOT MATCHED THEN
    INSERT (id, measuring_time_minutes, volume_ml, geometry, tare_mass_grams, version)
    VALUES (source.id, source.measuring_time_minutes, source.volume_ml,
            source.geometry, source.tare_mass_grams, source.version);

-- Immutable terminal records produced by the operator-controlled workflow.
CREATE TABLE IF NOT EXISTS manual_measurements
(
    id UUID PRIMARY KEY,
    sample_code VARCHAR(256) NOT NULL,
    gross_mass_grams NUMERIC(18, 6) NOT NULL,
    net_mass_grams NUMERIC(18, 6) NOT NULL,
    measuring_time_minutes BIGINT NOT NULL,
    volume_ml DOUBLE PRECISION NOT NULL,
    geometry VARCHAR(32) NOT NULL,
    tare_mass_grams DOUBLE PRECISION NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(32) NOT NULL,
    spectrum_reference TEXT NOT NULL,
    error_message TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_manual_measurements_sample
    ON manual_measurements (sample_code, started_at);

CREATE INDEX IF NOT EXISTS idx_manual_measurements_started
    ON manual_measurements (started_at);

-- One immutable row per object processed by an automatic production run.
CREATE TABLE IF NOT EXISTS automatic_measurements
(
    run_id UUID NOT NULL,
    object_number INTEGER NOT NULL CHECK (object_number > 0),
    sample_code VARCHAR(256) NOT NULL,
    coordinate_x DOUBLE PRECISION NOT NULL,
    coordinate_y DOUBLE PRECISION NOT NULL,
    gross_mass_grams NUMERIC(18, 6),
    net_mass_grams NUMERIC(18, 6),
    measuring_time_minutes BIGINT NOT NULL,
    volume_ml DOUBLE PRECISION NOT NULL,
    geometry VARCHAR(32) NOT NULL,
    tare_mass_grams DOUBLE PRECISION NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(32) NOT NULL,
    spectrum_reference TEXT NOT NULL,
    error_message TEXT NOT NULL,
    PRIMARY KEY (run_id, object_number)
);

CREATE INDEX IF NOT EXISTS idx_automatic_measurements_sample
    ON automatic_measurements (sample_code, started_at);

CREATE INDEX IF NOT EXISTS idx_automatic_measurements_started
    ON automatic_measurements (started_at);

-- Safety interlock state and immutable operator attribution for recovery.
CREATE TABLE IF NOT EXISTS scenario_incidents
(
    id UUID PRIMARY KEY,
    severity VARCHAR(16) NOT NULL,
    status VARCHAR(32) NOT NULL,
    source VARCHAR(128) NOT NULL,
    code VARCHAR(128) NOT NULL,
    message TEXT NOT NULL,
    run_id UUID,
    object_number INTEGER,
    workflow_step VARCHAR(64),
    raised_at TIMESTAMP WITH TIME ZONE NOT NULL,
    acknowledged_by VARCHAR(255),
    acknowledged_at TIMESTAMP WITH TIME ZONE,
    cleared_by VARCHAR(255),
    cleared_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_scenario_incidents_status
    ON scenario_incidents (status, raised_at);

COMMENT ON TABLE roles IS 'Справочник ролей пользователей RGSCenter';
COMMENT ON TABLE users IS 'Пользователи RGSCenter';
COMMENT ON COLUMN users.hash IS 'BCrypt-хэш пароля; пароль в открытом виде не хранится';
COMMENT ON TABLE auth_sessions IS 'Серверные сессии токен-аутентификации RGSCenter';
COMMENT ON TABLE device_settings IS 'Настройки подключения физических устройств';
COMMENT ON TABLE device_settings_audit IS 'Неизменяемая история настроек подключения';
COMMENT ON TABLE measurement_parameters IS 'Текущие параметры автоматического и ручного измерения';
COMMENT ON TABLE manual_measurements IS 'Результаты измерений, запущенных оператором в ручном режиме';
COMMENT ON TABLE automatic_measurements IS 'Результаты объектов автоматического производственного цикла';
COMMENT ON TABLE scenario_incidents IS 'Аварии сценария и подтверждения операторов';
