package com.rgs.center.peripheral;

/**
 * Состояние жизненного цикла worker внешнего устройства.
 */
public enum PeripheralWorkerState {
    /** Worker не запущен, транспорт закрыт. */
    STOPPED,
    /** Выполняется открытие и начальная очистка транспорта. */
    STARTING,
    /** RX/TX-потоки запущены и готовы обслуживать устройство. */
    RUNNING,
    /** Выполняется штатная остановка потоков и транспорта. */
    STOPPING,
    /** Работа прекращена из-за ошибки транспорта, буфера или протокола. */
    FAILED
}
