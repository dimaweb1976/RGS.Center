package com.rgs.center.connection;

/**
 * Базовый жизненный цикл соединения с внешним устройством.
 *
 * <p>Конкретное соединение может использовать COM, TCP, HTTP или другой
 * транспорт. Объект соединения владеет соответствующим системным ресурсом
 * от вызова {@link #open()} до вызова {@link #close()}.</p>
 */
public interface DeviceConnection extends AutoCloseable {

    /**
     * Открывает соединение и захватывает транспортный ресурс.
     *
     * @throws RuntimeException если соединение открыть невозможно
     */
    void open();

    /**
     * Проверяет, открыт ли транспортный ресурс.
     *
     * @return {@code true}, если соединение открыто
     */
    boolean isOpen();

    /**
     * Освобождает транспортный ресурс. Повторный вызов должен быть безопасным.
     */
    @Override
    void close();
}
