package com.rgs.center.web.wizard;

import java.time.Instant;
import java.util.List;

/** Read-only model of one service device screen. */
public record WizardServiceDeviceView(
        DeviceCard device,
        List<Section> sections,
        List<Communication> communications,
        List<Action> actions
) {
    public WizardServiceDeviceView {
        sections = List.copyOf(sections);
        communications = List.copyOf(communications);
        actions = List.copyOf(actions);
    }

    /** Compact card shared by the service overview and detail page. */
    public record DeviceCard(
            String code,
            String name,
            String endpoint,
            String protocol,
            String connection,
            String technical,
            String operation,
            String lastResponse,
            String reasons,
            String lastError,
            boolean enabled,
            boolean stale,
            String stateCssClass
    ) {
    }

    /** Logical group of protocol or device values. */
    public record Section(String title, List<Metric> metrics) {
        public Section {
            metrics = List.copyOf(metrics);
        }
    }

    public record Metric(String label, String value) {
    }

    /** Queue and transport counters from one peripheral worker. */
    public record Communication(
            String channel,
            String state,
            int commandQueueDepth,
            int receiveBufferBytes,
            int frameQueueDepth,
            long bytesReceived,
            long bytesSent,
            long framesReceived,
            long framesDropped,
            String lastReceive,
            String lastTransmit,
            String lastError
    ) {
    }

    /** Whitelisted service command; paths are generated by the backend. */
    public record Action(
            String code,
            String label,
            String description,
            boolean enabled,
            boolean dangerous
    ) {
    }

    /** Overview of all supported service devices. */
    public record Overview(Instant generatedAt, List<DeviceCard> devices) {
        public Overview {
            devices = List.copyOf(devices);
        }
    }
}
